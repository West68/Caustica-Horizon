"""Generate the 26.3 variants of Caustica's raster GLSL shaders from the 26.2 sources.

26.3 compiles core shaders with Vulkan GLSL rules: `#include` instead of `#moj_import`, separate shader
objects, and explicit locations on every vertex input and stage varying (matched by location, not name).
Litematica 26.3 also renamed its ChunkFix uniform block to LegacyTerrainFix.
Run from the repository root; writes src/main/resources-26.3/assets/caustica/shaders/.
"""
import pathlib
import re

SRC = pathlib.Path("src/main/resources/assets/caustica/shaders")
DST = pathlib.Path("src/main/resources-26.3/assets/caustica/shaders")
HEADER = "// GENERATED by tools/port/make_263_shaders.py from src/main/resources - edit the 26.2 source and regenerate.\n"

# Vertex attribute locations follow the vertex format order (BLOCK: Position, Color, UV0, UV2).
ATTRIBUTES = {"Position": 0, "Color": 1, "UV0": 2, "UV2": 3}
# litematica_pbr varyings: the first four match Litematica's legacy_terrain.vsh order.
VARYINGS = {"sphericalVertexDistance": 0, "cylindricalVertexDistance": 1, "vertexColor": 2,
            "texCoord0": 3, "ceViewPosition": 5}  # 4 is legacy_terrain's chunkVisibility


def convert(name: str, text: str) -> str:
    text = text.replace("#moj_import", "#include")
    text = re.sub(r"^(#version \d+[^\n]*\n)", r"\1#extension GL_ARB_separate_shader_objects : require\n", text, count=1)
    text = re.sub(r"\buniform ChunkFix\b", "uniform LegacyTerrainFix", text)
    stage = name.rsplit(".", 1)[1]

    def place(m):
        qual, decl_type, var = m.group(1), m.group(2), m.group(3)
        if name == "schematic_overlay_depth.fsh" and qual == "in" and var == "vertexColor":
            loc = "CE_VERTEX_COLOR_LOCATION"
        elif qual == "out" and stage == "fsh":
            loc = 0
        elif qual == "in" and stage == "vsh":
            loc = ATTRIBUTES[var]
        elif name == "rt_depth_fill.fsh" and var == "texCoord":
            loc = 0  # screenquad.vsh
        else:
            loc = VARYINGS[var]
        return f"layout(location = {loc}) {qual} {decl_type} {var};"

    text = re.sub(r"^(in|out)\s+(\w+)\s+(\w+)\s*;", place, text, flags=re.M)
    if name == "schematic_overlay_depth.fsh":
        text = text.replace("#extension GL_ARB_separate_shader_objects : require\n",
                            "#extension GL_ARB_separate_shader_objects : require\n"
                            "#ifndef CE_VERTEX_COLOR_LOCATION\n#define CE_VERTEX_COLOR_LOCATION 0\n#endif\n", 1)
    first_newline = text.index("\n") + 1  # keep #version first
    return text[:first_newline] + HEADER + text[first_newline:]


DST.mkdir(parents=True, exist_ok=True)
for f in sorted(SRC.glob("*.[vf]sh")):
    out = convert(f.name, f.read_text(encoding="utf-8"))
    (DST / f.name).write_text(out, encoding="utf-8", newline="\n")
    print("wrote", DST / f.name)
